"""commands.py - Auto-eligible command registry for AI.py v6.2.0.

Loads command mappings from auto_commands.json (generated by extract_commands.py).
Dispatches ~4,250 simple commands via function name lookup.

Complex commands (HBPE, input, etc.) stay in AI.py's handle_cmd.
"""
import json as _json
import os as _os

_DATA = None

def _load():
    global _DATA
    if _DATA is None:
        _p = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                           '..', '..', 'scripts', 'auto_commands.json')
        if _os.path.isfile(_p):
            with open(_p, encoding='utf-8') as _f:
                _DATA = _json.load(_f)
        else:
            _DATA = {'try_print': {}, 'direct_print': {}, 'data_preview': {}}
    return _DATA

def _try_print(fn_name, ns):
    try:
        print(ns[fn_name]())
    except Exception as _e:
        print(_e)

def _direct_print(fn_name, ns):
    print(ns[fn_name]())

def _data_preview(fn_name, ns):
    try:
        _d = ns[fn_name]()
        print("{}: {} entries. First:".format(fn_name, len(_d)))
        for _x in _d[:2]:
            print("  ", _x)
    except Exception as _e:
        print("Error:", _e)

def dispatch_auto(cmd, namespace):
    """Try to dispatch cmd via auto-registry. Returns True if handled."""
    d = _load()
    if cmd in d.get('try_print', {}):
        _try_print(d['try_print'][cmd], namespace)
        return True
    if cmd in d.get('direct_print', {}):
        _direct_print(d['direct_print'][cmd], namespace)
        return True
    if cmd in d.get('data_preview', {}):
        _data_preview(d['data_preview'][cmd], namespace)
        return True
    return False
